"""Opt-in compact pair identity; frozen V0/V1 and semantic controllers stay intact."""

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Annotated, ClassVar, Literal

from pydantic import Field, StrictStr, create_model, model_validator

from paper_research.agents.research_agent.compact_verifier import (
    RATIONALE_NOT_REQUESTED,
    assessment_input,
    build_contract_verifier,
)
from paper_research.agents.research_agent.contract_verifier import StructuredContractAdapter
from paper_research.agents.research_agent.evidence_contract import (
    EvidenceAssessment,
    StrictModel,
    Verdict,
)
from paper_research.providers.llm import LLMProviderError

# Preserve the existing AssessmentBatch bound; 30 is the largest observed workload.
MAX_PAIRS = 80
Confidence = Annotated[float, Field(ge=0, le=1, strict=True, allow_inf_nan=False)]


@dataclass(frozen=True)
class PairIdentity:
    pair_id: str
    requirement_id: str
    evidence_id: str


@dataclass(frozen=True)
class PairIdentityMap:
    entries: tuple[PairIdentity, ...]

    def __post_init__(self):
        if not isinstance(self.entries, tuple) or not 1 <= len(self.entries) <= MAX_PAIRS:
            raise ValueError("SCHEMA_INVALID: invalid code-owned pair map")
        if self.expected_ids != tuple(f"p{i:02d}" for i in range(len(self.entries))):
            raise ValueError("SCHEMA_INVALID: pair IDs must be generated by code")
        pairs = [(p.requirement_id, p.evidence_id) for p in self.entries]
        if len(set(pairs)) != len(pairs):
            raise ValueError("SCHEMA_INVALID: duplicate pair mapping")

    @classmethod
    def build(cls, requirement_ids, evidence_ids):
        if not requirement_ids or not evidence_ids:
            raise ValueError("SCHEMA_INVALID: empty expected pair set")
        if len(set(requirement_ids)) != len(requirement_ids):
            raise ValueError("SCHEMA_INVALID: duplicate input requirement ID")
        if len(set(evidence_ids)) != len(evidence_ids):
            raise ValueError("SCHEMA_INVALID: duplicate input evidence ID")
        pairs = [(r, e) for r in requirement_ids for e in evidence_ids]
        if len(pairs) > MAX_PAIRS:
            raise ValueError("SCHEMA_INVALID: existing maximum pair bound exceeded")
        return cls(tuple(PairIdentity(f"p{i:02d}", r, e) for i, (r, e) in enumerate(pairs)))

    @property
    def expected_ids(self):
        return tuple(p.pair_id for p in self.entries)

    def as_input(self):
        return {
            "columns": ["pair_id", "requirement_id", "evidence_id"],
            "rows": [[p.pair_id, p.requirement_id, p.evidence_id] for p in self.entries],
        }

    def encode(self, assessments):
        mapping = {(p.requirement_id, p.evidence_id): p.pair_id for p in self.entries}
        rows = []
        for assessment in assessments:
            a = EvidenceAssessment.model_validate(assessment)
            key = (a.requirement_id, a.evidence_id)
            if key not in mapping:
                raise ValueError("SCHEMA_INVALID: unknown assessment pair")
            rows.append([mapping[key], a.verdict, a.confidence])
        return pair_schema(len(self.entries)).model_validate({"a": rows})


class PairAssessmentBatch(StrictModel):
    a: list[tuple[StrictStr, Verdict, Confidence]] = Field(
        min_length=1, max_length=MAX_PAIRS,
        description="Every code-owned pair ID exactly once: [pair_id, verdict, confidence].",
    )
    expected_ids: ClassVar[tuple[str, ...]] = ()

    @model_validator(mode="after")
    def complete_pair_ids(self):
        if self.expected_ids:
            ids = [row[0] for row in self.a]
            if len(ids) != len(set(ids)):
                raise ValueError("SCHEMA_INVALID: duplicate pair ID")
            if set(ids) != set(self.expected_ids):
                raise ValueError("SCHEMA_INVALID: missing or unknown pair ID")
        return self


@lru_cache(maxsize=MAX_PAIRS)
def pair_schema(pair_count):
    if not 1 <= pair_count <= MAX_PAIRS:
        raise ValueError("SCHEMA_INVALID: unsupported pair count")
    ids = tuple(f"p{i:02d}" for i in range(pair_count))
    row = tuple[Literal[ids], Verdict, Confidence]
    schema = create_model(
        f"PairAssessmentBatch{pair_count}", __base__=PairAssessmentBatch,
        a=(list[row], Field(min_length=pair_count, max_length=pair_count,
                           description="Copy all supplied pair IDs exactly once; no new IDs.")),
    )
    schema.expected_ids = ids
    return schema


def decode_pairs(batch, identities):
    # All shape/ID/cardinality checks occur before constructing any semantic row.
    parsed = pair_schema(len(identities.entries)).model_validate(batch)
    mapping = {p.pair_id: p for p in identities.entries}
    return [EvidenceAssessment(
        requirement_id=mapping[p].requirement_id,
        evidence_id=mapping[p].evidence_id,
        verdict=v, confidence=c, rationale=RATIONALE_NOT_REQUESTED,
    ) for p, v, c in parsed.a]


def strict_pair_json(text):
    def unique_object(pairs):
        output = {}
        for key, value in pairs:
            if key in output:
                raise ValueError("SCHEMA_INVALID: duplicate JSON key")
            output[key] = value
        return output

    def reject_constant(value):
        raise ValueError("SCHEMA_INVALID: non-finite JSON number: " + value)

    parsed = json.loads(text, object_pairs_hook=unique_object, parse_constant=reject_constant)
    if not isinstance(parsed, dict):
        raise ValueError("SCHEMA_INVALID: expected JSON object")
    return parsed


class StrictPairJSONBoundary:
    """Reparse immutable provider raw text; no HTTP, retry or semantic repair here."""

    def __init__(self, provider):
        self.provider = provider

    def __getattr__(self, name):
        return getattr(self.provider, name)

    def generate_structured_json(self, **kwargs):
        result = self.provider.generate_structured_json(**kwargs)
        if not kwargs["schema_name"].startswith("phase2a_PairAssessmentBatch"):
            return result
        try:
            if len(result.usage_records) != 1:
                raise ValueError("SCHEMA_INVALID: exact raw response required")
            record = result.usage_records[0]
            if record.finish_reason == "length":
                raise ValueError("SCHEMA_INVALID: truncated response")
            if not record.raw_response_path:
                raise ValueError("SCHEMA_INVALID: missing raw response")
            saved = json.loads(Path(record.raw_response_path).read_text(encoding="utf-8"))
            parsed = strict_pair_json(saved["raw_content"])
            if parsed != result.payload:
                raise ValueError("SCHEMA_INVALID: parsed/raw response mismatch")
        except (KeyError, OSError, TypeError, ValueError) as exc:
            # Existing _request accounts this billed response and permits only its original
            # second schema attempt. The wrapper never dispatches another request itself.
            raise LLMProviderError(
                str(exc), error_code="STRUCTURED_JSON_RESPONSE_ERROR",
                api_request_count=result.request_attempt_count, usage_records=result.usage_records,
            ) from exc
        return result


class PairIdentityContractAdapter(StructuredContractAdapter):
    def __init__(self, provider):
        super().__init__(provider)
        self.provider = StrictPairJSONBoundary(provider)

    def assess(self, state, requirement_ids, evidence_ids, runner):
        payload = assessment_input(state, requirement_ids, evidence_ids)
        # Follow the original payload requirement order, not incidental caller order.
        mapping = PairIdentityMap.build(
            [r["requirement_id"] for r in payload["requirements"]], evidence_ids)
        payload["pair_identity_map"] = mapping.as_input()
        batch = self._request(state, runner, pair_schema(len(mapping.entries)),
                              payload, "VERIFIER_FAILURE")
        return decode_pairs(batch, mapping)


def build_pair_contract_verifier(provider, *, verifier_protocol="v0"):
    if verifier_protocol == "v1_1_compact_pair_id":
        return PairIdentityContractAdapter(provider)
    return build_contract_verifier(provider, verifier_protocol=verifier_protocol)
